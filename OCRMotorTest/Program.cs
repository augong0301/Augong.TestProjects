	public class SerialConnection
	{
		private const string NewLine = "\r\n";
		private const int DataBits = 8;
		private const StopBits _StopBits = StopBits.One;
		private const Parity _Parity = Parity.None;
		private SerialPort mSerialPort;

		public bool IsOpened
		{
			get
			{
				return mSerialPort != null && mSerialPort.IsOpen;
			}
		}
		public SerialConnection(string portName, int baudRate)
		{
			mSerialPort = new SerialPort(portName, baudRate, _Parity, DataBits, _StopBits);
			mSerialPort.NewLine = NewLine;
			mSerialPort.ReadTimeout = 30000;
			mSerialPort.WriteTimeout = 30000;
			Open();
		}

		public void Open()
		{
			if (IsOpened) return;

			mSerialPort.Open();
		}

		public void Close()
		{
			if (!IsOpened) return;

			mSerialPort.Close();
		}
		public void Send(byte[] bytes)
		{
			mSerialPort.Write(bytes, 0, bytes.Length);
		}
		public void Send(string command, params string[] parameters)
		{
			if (!IsOpened) return;

			var builder = new StringBuilder(command);

			if (parameters != null && parameters.Length > 0)
			{
				for (int i = 0; i < parameters.Length; i++)
				{
					builder.Append($" {parameters[i]}");
				}
			}

			mSerialPort.WriteLine(builder.ToString());
		}

		public string Receive()
		{
			return mSerialPort.ReadLine();
		}
	}

